// The pieces of an install. setup.ts decides what to install (wizard or --yes); this file does it.

const RC_START = "# >>> bouncer >>>";
const RC_END = "# <<< bouncer <<<";
const plistPath = () => join(userHome(), "Library", "LaunchAgents", `${launchdLabel()}.plist`);

export function shimScript(tool: string): string {
  return `#!/bin/sh
# Bouncer shim for ${tool}. Generated by \`bouncer install\`, removed by \`bouncer uninstall\`.
# Nested calls (inside a job) and the bypass variable go straight to the real ${tool}.
# "Is this me?" is decided by file identity (-ef), not by how PATH spells the folder, and a depth
# guard stops a loop if anything still points back here.
BOUNCER_SHIM_DEPTH=$(( \${BOUNCER_SHIM_DEPTH:-0} + 1 )); export BOUNCER_SHIM_DEPTH
if [ "$BOUNCER_SHIM_DEPTH" -gt 4 ]; then echo "bouncer: ${tool}: shim loop, check PATH (bouncer doctor)" >&2; exit 126; fi
if [ -n "$BOUNCER_JOB" ] || [ -n "$BOUNCER_BYPASS" ] || [ ! -x "${paths.binary}" ]; then
  set -f; IFS=:
  for d in $PATH; do
    [ -n "$d" ] || continue
    [ -x "$d/${tool}" ] && [ ! -d "$d/${tool}" ] || continue
    [ "$d/${tool}" -ef "$0" ] && continue
    [ "$d" -ef "${paths.shimDir}" ] && continue
    exec "$d/${tool}" "$@"
  done
  echo "bouncer: ${tool}: command not found" >&2
  exit 127
fi
exec "${paths.binary}" shim ${tool} "$@"
`;
}

function plist(pathEnv: string): string {
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>${launchdLabel()}</string>
  <key>ProgramArguments</key>
  <array><string>${paths.binary}</string><string>daemon</string></array>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><true/>
  <key>ProcessType</key><string>Interactive</string>
  <key>EnvironmentVariables</key>
  <dict>
    <key>PATH</key><string>${pathEnv}</string>
    <key>HOME</key><string>${userHome()}</string>
  </dict>
  <key>StandardOutPath</key><string>${paths.home}/daemon.stdout.log</string>
  <key>StandardErrorPath</key><string>${paths.home}/daemon.stdout.log</string>
</dict>
</plist>
`;
}

function launchctl(args: string[]): number {
  return Bun.spawnSync(["/bin/launchctl", ...args], { stdout: "ignore", stderr: "ignore" }).exitCode;
}

/** `bootout` returns before the service is gone; a bootstrap issued too early silently fails. */
function bootoutAndWait(domain: string): void {
  if (launchctl(["bootout", `${domain}/${launchdLabel()}`]) !== 0) return;
  for (let i = 0; i < 50; i++) {
    if (launchctl(["print", `${domain}/${launchdLabel()}`]) !== 0) return;
    Bun.sleepSync(100);
  }
}

function waitForSocket(ms: number): boolean {
  for (let waited = 0; waited < ms; waited += 100) {
    if (existsSync(paths.socket)) return true;
    Bun.sleepSync(100);
  }
  return false;
}

const cmuxConfigDir = () => join(userHome(), ".config", "cmux");
const cmuxDock = () => join(cmuxConfigDir(), "dock.json");
const DOCK_ID = "bouncer";

export function hasCmux(): boolean {
  return existsSync(cmuxConfigDir()) || existsSync("/Applications/cmux.app");
}

function editCmuxDock(add: boolean): boolean {
  // Never create cmux's config on a Mac without cmux.
  if (add ? !hasCmux() : !existsSync(cmuxConfigDir())) return false;
  const file = cmuxDock();
  const config = readJson(file);
  const controls = ((config.controls ?? []) as { id?: string }[]).filter((c) => c.id !== DOCK_ID);
  if (add) controls.push({ id: DOCK_ID, title: "Bouncer", command: `"${paths.binary}" watch`, height: 420 } as never);
  if (!add && !existsSync(file)) return false;
  backup(file);
  if (!add && !controls.length && Object.keys(config).length <= 1) rmSync(file, { force: true });
  else writeJson(file, { ...config, controls });
  return true;
}

/**
 * Shell startup files that must carry the PATH line. A fresh macOS account has none, so the
 * file for the user's login shell is created: zsh reads ~/.zshrc, and bash on macOS runs login
 * shells, which read ~/.bash_profile (not ~/.bashrc).
 */
function rcFiles(create: boolean): string[] {
  const shell = basename(process.env.SHELL || "/bin/zsh");
  const wanted = shell === "bash" ? [".bash_profile"] : shell === "zsh" ? [".zshrc"] : [];
  const files = new Set<string>();
  for (const f of [".zshrc", ".bash_profile", ".bashrc"]) {
    const path = join(userHome(), f);
    if (existsSync(path)) files.add(path);
  }
  if (create) {
    for (const f of wanted) {
      const path = join(userHome(), f);
      if (!existsSync(path)) writeFileSync(path, "", { mode: 0o644 });
      files.add(path);
    }
  }
  return [...files];
}

function editRc(file: string, add: boolean): void {
  let text = stripBlock(readFileSync(file, "utf8"), RC_START, RC_END);
  if (add) {
    // Appended last so it lands in front of every other PATH entry the file prepends.
    text += `${text ? "\n" : ""}${RC_START}\nexport PATH="${paths.shimDir}:$PATH"\n${RC_END}\n`;
  }
  writeAtomic(file, text);
}

/**
 * (Re)write one shim per gated tool, from the current policy, and remove shims for tools that
 * are no longer gated. Returns the tools shimmed.
 */
export function writeShims(): string[] {
  mkdirSync(paths.shimDir, { recursive: true });
  let tools: string[];
  try {
    tools = shimmedTools(loadPolicy().tools);
  } catch (e) {
    console.error(`bouncer: policy.yaml is invalid (${(e as Error).message}); using the default tools`);
    tools = shimmedTools();
  }
  for (const existing of readdirSync(paths.shimDir)) {
    if (existing !== "bouncer" && !tools.includes(existing)) rmSync(join(paths.shimDir, existing), { force: true });
  }
  for (const tool of tools) {
    const file = join(paths.shimDir, tool);
    writeFileSync(file, shimScript(tool));
    chmodSync(file, 0o755);
  }
  // The shim dir is on PATH anyway, so `bouncer` itself lives there too.
  rmSync(join(paths.shimDir, "bouncer"), { force: true });
  symlinkSync(paths.binary, join(paths.shimDir, "bouncer"));
  return tools;
}

/**
 * `/opt/homebrew/Cellar/bouncer/0.4.0/bin/bouncer` → `/opt/homebrew/opt/bouncer/bin/bouncer`,
 * the path Homebrew keeps pointing at the current version. Null when not run from Homebrew.
 */
export function homebrewStablePath(execPath: string): string | null {
  const m = execPath.match(/^(.*)\/Cellar\/([^/]+)\/[^/]+\/bin\/([^/]+)$/);
  if (!m) return null;
  const stable = `${m[1]}/opt/${m[2]}/bin/${m[3]}`;
  return existsSync(stable) ? stable : null;
}

/** Homebrew's version-independent path to an installed Bouncer, if Homebrew has one. */
export function homebrewInstall(
  prefixes: (string | undefined)[] = [process.env.HOMEBREW_PREFIX, "/opt/homebrew", "/usr/local"],
): string | null {
  for (const prefix of prefixes) {
    if (!prefix) continue;
    const bin = `${prefix}/opt/bouncer/bin/bouncer`;
    if (existsSync(bin)) return bin;
  }
  return null;
}

/**
 * Which Homebrew binary this install should copy and follow, or null for none. Run from
 * Homebrew: that one. Run from the installed copy (once Bouncer is set up, `bouncer` on PATH
 * resolves to ~/.bouncer/bin/bouncer, ahead of Homebrew's) on a Mac that also has Homebrew's:
 * adopt it, or `brew upgrade` would never reach the daemon.
 */
export function homebrewSource(execPath: string, installed: string, findBrew = homebrewInstall): string | null {
  return homebrewStablePath(execPath) ?? (execPath === installed ? findBrew() : null);
}

export function step(ok: boolean, label: string, detail: string): void {
  console.log(`${ok ? mark.ok() : mark.fail()} ${label.padEnd(12)} ${out.dim(detail.replaceAll(userHome(), "~"))}`);
}

export interface InstallPlan {
  /** Agent ids to connect; every other known agent is disconnected. */
  agents: string[];
  statusLine: boolean;
  cmuxDock: boolean;
  /** Policy file content to write, or null to keep the existing one. */
  policy: string | null;
  policyNote: string;
}

/** Do the install. Returns whether the daemon came up. */
export function performInstall(plan: InstallPlan): boolean {
  mkdirSync(paths.home, { recursive: true, mode: 0o700 });
  chmodSync(paths.home, 0o700);
  mkdirSync(paths.shimDir, { recursive: true });

  const brew = homebrewSource(process.execPath, paths.binary);
  const tmpBin = `${paths.binary}.new`;
  rmSync(tmpBin, { force: true });
  if (brew) {
    // A real copy, not a link: if `brew uninstall` runs first, ~/.bouncer/bouncer still works
    // (hooks, `bouncer uninstall`). The daemon watches Homebrew's version-independent path and
    // copies an upgrade over when it's idle.
    copyFileSync(brew, tmpBin);
    chmodSync(tmpBin, 0o755);
    renameSync(tmpBin, paths.binary);
    writeFileSync(paths.source, `${brew}\n`, { mode: 0o600 });
    step(true, "binary", `${paths.binary} (follows Homebrew upgrades)`);
  } else if (process.execPath !== paths.binary) {
    rmSync(paths.source, { force: true });
    copyFileSync(process.execPath, tmpBin);
    chmodSync(tmpBin, 0o755);
    renameSync(tmpBin, paths.binary);
    step(true, "binary", paths.binary);
  } else step(true, "binary", `${paths.binary} (already in place)`);

  if (plan.policy !== null) {
    if (existsSync(paths.policy)) backup(paths.policy);
    writeFileSync(paths.policy, plan.policy, { mode: 0o600 });
    chmodSync(paths.policy, 0o600);
  }
  step(true, "policy", plan.policyNote);

  step(true, "shims", writeShims().join(" "));

  const pathEnv = (process.env.PATH ?? "/usr/bin:/bin")
    .split(":")
    .filter((d) => d && d !== paths.shimDir)
    .join(":");
  mkdirSync(join(userHome(), "Library", "LaunchAgents"), { recursive: true });
  writeFileSync(plistPath(), plist(pathEnv));
  const domain = `gui/${process.getuid?.() ?? 501}`;
  bootoutAndWait(domain);
  const code = launchctl(["bootstrap", domain, plistPath()]);
  const daemonUp = code === 0 && waitForSocket(5000);
  step(
    daemonUp,
    "daemon",
    daemonUp ? `running (launchd ${launchdLabel()})` : `did not start (launchctl exited ${code}), see ${paths.log}`,
  );

  for (const agent of agents({ statusLine: plan.statusLine })) {
    if (plan.agents.includes(agent.id)) {
      const changed = agent.connect();
      step(true, agent.name, changed.length ? changed.join(", ") : "connected (builds queued by shims)");
    } else if (agent.connected() && agent.level !== "shims") {
      // Unchecked in the wizard: take back what an earlier install added.
      for (const file of agent.disconnect()) step(true, agent.name, `disconnected (${file})`);
    }
  }

  if (plan.cmuxDock && editCmuxDock(true)) step(true, "cmux", `Dock control in ${cmuxDock()}`);
  if (!plan.cmuxDock && existsSync(cmuxDock()) && JSON.stringify(readJson(cmuxDock())).includes(`"${DOCK_ID}"`)) {
    editCmuxDock(false);
  }

  const rcs = rcFiles(true);
  for (const file of rcs) {
    backup(file);
    editRc(file, true);
    step(true, "PATH", file);
  }
  if (!rcs.length) {
    step(false, "PATH", `no zsh/bash startup file for ${process.env.SHELL}; add ${paths.shimDir} to PATH yourself`);
  }
  return daemonUp;
}

export function uninstall(args: string[]): void {
  console.log(out.bold("Removing Bouncer\n"));
  bootoutAndWait(`gui/${process.getuid?.() ?? 501}`);
  rmSync(plistPath(), { force: true });
  step(true, "daemon", "stopped and removed from launchd");
  // Every known agent, not just the saved choices: nothing may be left behind.
  for (const agent of agents()) {
    for (const file of agent.disconnect()) step(true, agent.name, `disconnected (${file})`);
  }
  if (editCmuxDock(false)) step(true, "cmux", "Dock control removed");
  for (const file of rcFiles(false)) {
    if (!readFileSync(file, "utf8").includes(RC_START)) continue;
    backup(file);
    editRc(file, false);
    step(true, "PATH", `line removed from ${file}`);
  }
  rmSync(paths.shimDir, { recursive: true, force: true });
  step(true, "shims", "removed");
  if (args.includes("--purge")) {
    rmSync(paths.home, { recursive: true, force: true });
    step(true, "data", `${paths.home} deleted`);
  } else {
    console.log(
      out.dim(
        `\nHistory, policy and setup kept in ${paths.home.replace(userHome(), "~")}. Remove with: bouncer uninstall --purge`,
      ),
    );
  }
}
