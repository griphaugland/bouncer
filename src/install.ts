import {
  chmodSync,
  copyFileSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  renameSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import { shimmedTools } from "./classify";
import { LAUNCHD_LABEL, paths } from "./paths";
import { DEFAULT_POLICY_YAML, loadPolicy } from "./policy";

const RC_START = "# >>> bouncer >>>";
const RC_END = "# <<< bouncer <<<";
const HOOK_MARK = "bouncer hook";
const plistPath = join(homedir(), "Library", "LaunchAgents", `${LAUNCHD_LABEL}.plist`);

function stamp(): string {
  return new Date().toISOString().slice(0, 19).replace(/[:T]/g, "-");
}

function backup(file: string): void {
  if (existsSync(file)) copyFileSync(file, `${file}.bak-bouncer-${stamp()}`);
}

function writeAtomic(file: string, content: string): void {
  const tmp = `${file}.tmp-bouncer`;
  writeFileSync(tmp, content);
  renameSync(tmp, file);
}

function shimScript(tool: string): string {
  return `#!/bin/sh
# Bouncer shim for ${tool}. Generated by \`bouncer install\`, removed by \`bouncer uninstall\`.
# Nested calls (inside a job) and BOUNCER_BYPASS=1 go straight to the real ${tool}.
if [ -n "$BOUNCER_JOB" ] || [ -n "$BOUNCER_BYPASS" ] || [ ! -x "${paths.binary}" ]; then
  set -f; IFS=:
  for d in $PATH; do
    [ "$d" = "${paths.shimDir}" ] && continue
    if [ -x "$d/${tool}" ] && [ ! -d "$d/${tool}" ]; then exec "$d/${tool}" "$@"; fi
  done
  echo "bouncer: ${tool}: command not found" >&2
  exit 127
fi
exec "${paths.binary}" shim ${tool} "$@"
`;
}

function plist(pathEnv: string): string {
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>${LAUNCHD_LABEL}</string>
  <key>ProgramArguments</key>
  <array><string>${paths.binary}</string><string>daemon</string></array>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><true/>
  <key>ProcessType</key><string>Interactive</string>
  <key>EnvironmentVariables</key>
  <dict>
    <key>PATH</key><string>${pathEnv}</string>
    <key>HOME</key><string>${homedir()}</string>
  </dict>
  <key>StandardOutPath</key><string>${paths.home}/daemon.stdout.log</string>
  <key>StandardErrorPath</key><string>${paths.home}/daemon.stdout.log</string>
</dict>
</plist>
`;
}

function launchctl(args: string[]): number {
  return Bun.spawnSync(["/bin/launchctl", ...args], { stdout: "ignore", stderr: "ignore" }).exitCode;
}

/** `bootout` returns before the service is gone; a bootstrap issued too early silently fails. */
function bootoutAndWait(domain: string): void {
  if (launchctl(["bootout", `${domain}/${LAUNCHD_LABEL}`]) !== 0) return;
  for (let i = 0; i < 50; i++) {
    if (launchctl(["print", `${domain}/${LAUNCHD_LABEL}`]) !== 0) return;
    Bun.sleepSync(100);
  }
}

function waitForSocket(ms: number): boolean {
  for (let waited = 0; waited < ms; waited += 100) {
    if (existsSync(paths.socket)) return true;
    Bun.sleepSync(100);
  }
  return false;
}

/** Claude Code settings files to wire hooks into: the default profile plus CLAUDE_CONFIG_DIR. */
function settingsFiles(): string[] {
  const files = new Set([join(homedir(), ".claude", "settings.json")]);
  if (process.env.CLAUDE_CONFIG_DIR) files.add(join(process.env.CLAUDE_CONFIG_DIR, "settings.json"));
  return [...files].filter((f) => existsSync(f));
}

type HookGroup = { matcher?: string; hooks: { type: string; command: string; timeout?: number }[] };

function withoutBouncer(groups: HookGroup[] | undefined): HookGroup[] {
  return (groups ?? [])
    .map((g) => ({ ...g, hooks: g.hooks.filter((h) => !h.command?.includes(HOOK_MARK)) }))
    .filter((g) => g.hooks.length > 0);
}

function editHooks(file: string, add: boolean): void {
  const settings = JSON.parse(readFileSync(file, "utf8"));
  settings.hooks ??= {};
  settings.hooks.PreToolUse = withoutBouncer(settings.hooks.PreToolUse);
  settings.hooks.UserPromptSubmit = withoutBouncer(settings.hooks.UserPromptSubmit);
  if (add) {
    settings.hooks.PreToolUse.push({
      matcher: "Bash",
      hooks: [{ type: "command", command: `${paths.binary} hook pre-tool`, timeout: 5 }],
    });
    settings.hooks.UserPromptSubmit.push({
      hooks: [{ type: "command", command: `${paths.binary} hook prompt`, timeout: 5 }],
    });
  }
  for (const key of ["PreToolUse", "UserPromptSubmit"]) {
    if (!settings.hooks[key].length) delete settings.hooks[key];
  }
  writeAtomic(file, `${JSON.stringify(settings, null, 2)}\n`);
}

// Appended verbatim to an existing statusLine command, so uninstall can strip exactly this.
const STATUS_SUFFIX = `; printf ' '; "${paths.binary}" status --segment 2>/dev/null`;
const STATUS_ONLY = `"${paths.binary}" status --segment 2>/dev/null`;

function editStatusLine(file: string, add: boolean): void {
  const settings = JSON.parse(readFileSync(file, "utf8"));
  const current: string | undefined = settings.statusLine?.type === "command" ? settings.statusLine.command : undefined;
  if (current === STATUS_ONLY) delete settings.statusLine;
  else if (current?.endsWith(STATUS_SUFFIX)) settings.statusLine.command = current.slice(0, -STATUS_SUFFIX.length);
  if (add) {
    if (settings.statusLine?.type === "command") settings.statusLine.command += STATUS_SUFFIX;
    else if (!settings.statusLine) settings.statusLine = { type: "command", command: STATUS_ONLY };
    else return; // some other statusLine type: leave it alone
  }
  writeAtomic(file, `${JSON.stringify(settings, null, 2)}\n`);
}

const cmuxDock = join(homedir(), ".config", "cmux", "dock.json");
const DOCK_ID = "bouncer";

function editCmuxDock(add: boolean): boolean {
  if (!existsSync(join(homedir(), ".config", "cmux"))) return false;
  const config = existsSync(cmuxDock) ? JSON.parse(readFileSync(cmuxDock, "utf8")) : { controls: [] };
  config.controls = (config.controls ?? []).filter((c: { id?: string }) => c.id !== DOCK_ID);
  if (add) config.controls.push({ id: DOCK_ID, title: "Bouncer", command: `"${paths.binary}" watch`, height: 420 });
  if (!add && !config.controls.length && Object.keys(config).length === 1) rmSync(cmuxDock, { force: true });
  else writeAtomic(cmuxDock, `${JSON.stringify(config, null, 2)}\n`);
  return true;
}

function rcFiles(): string[] {
  return [".zshrc", ".bashrc"].map((f) => join(homedir(), f)).filter((f) => existsSync(f));
}

function stripBlock(text: string): string {
  const start = text.indexOf(RC_START);
  const end = text.indexOf(RC_END);
  if (start < 0 || end < start) return text;
  return (text.slice(0, start).replace(/\n+$/, "\n") + text.slice(end + RC_END.length).replace(/^\n/, "")).trimEnd() + "\n";
}

function editRc(file: string, add: boolean): void {
  let text = stripBlock(readFileSync(file, "utf8"));
  if (add) {
    // Appended last so it lands in front of every other PATH entry the file prepends.
    text += `\n${RC_START}\nexport PATH="${paths.shimDir}:$PATH"\n${RC_END}\n`;
  }
  writeAtomic(file, text);
}

/**
 * (Re)write one shim per gated tool, from the current policy, and remove shims for tools that
 * are no longer gated. Returns the tools shimmed.
 */
export function writeShims(): string[] {
  mkdirSync(paths.shimDir, { recursive: true });
  let tools: string[];
  try {
    tools = shimmedTools(loadPolicy().tools);
  } catch (e) {
    console.error(`bouncer: policy.yaml is invalid (${(e as Error).message}); using the default tools`);
    tools = shimmedTools();
  }
  for (const existing of readdirSync(paths.shimDir)) {
    if (existing !== "bouncer" && !tools.includes(existing)) rmSync(join(paths.shimDir, existing), { force: true });
  }
  for (const tool of tools) {
    const file = join(paths.shimDir, tool);
    writeFileSync(file, shimScript(tool));
    chmodSync(file, 0o755);
  }
  // The shim dir is on PATH anyway, so `bouncer` itself lives there too.
  rmSync(join(paths.shimDir, "bouncer"), { force: true });
  symlinkSync(paths.binary, join(paths.shimDir, "bouncer"));
  return tools;
}

export function install(): void {
  // Must run from the compiled binary: that is what gets copied into ~/.bouncer.
  if (/(^|\/)bun$/.test(process.execPath)) {
    console.error("bouncer install must run from the compiled binary: bun run build && ./dist/bouncer install");
    process.exit(1);
  }

  mkdirSync(paths.home, { recursive: true, mode: 0o700 });
  chmodSync(paths.home, 0o700);
  mkdirSync(paths.shimDir, { recursive: true });
  const tmpBin = `${paths.binary}.new`;
  copyFileSync(process.execPath, tmpBin);
  chmodSync(tmpBin, 0o755);
  renameSync(tmpBin, paths.binary);
  console.log(`✓ binary      ${paths.binary}`);

  if (!existsSync(paths.policy)) {
    writeFileSync(paths.policy, DEFAULT_POLICY_YAML, { mode: 0o600 });
    console.log(`✓ policy      ${paths.policy}`);
  } else console.log(`· policy      ${paths.policy} (kept)`);

  const tools = writeShims();
  console.log(`✓ shims       ${tools.join(", ")} (+ bouncer)`);

  const pathEnv = (process.env.PATH ?? "/usr/bin:/bin")
    .split(":")
    .filter((d) => d && d !== paths.shimDir)
    .join(":");
  mkdirSync(join(homedir(), "Library", "LaunchAgents"), { recursive: true });
  writeFileSync(plistPath, plist(pathEnv));
  const domain = `gui/${process.getuid?.() ?? 501}`;
  bootoutAndWait(domain);
  const code = launchctl(["bootstrap", domain, plistPath]);
  if (code === 0 && waitForSocket(5000)) console.log(`✓ daemon      launchd ${LAUNCHD_LABEL}, answering on ${paths.socket}`);
  else console.log(`✗ daemon      not answering (launchctl bootstrap exited ${code}); see ${paths.log}`);

  for (const file of settingsFiles()) {
    backup(file);
    editHooks(file, true);
    editStatusLine(file, true);
    console.log(`✓ hooks       ${file} (+ statusline segment)`);
  }
  if (existsSync(cmuxDock)) backup(cmuxDock);
  if (editCmuxDock(true)) console.log(`✓ cmux dock   ${cmuxDock} (seeds new windows; existing Docks: add a terminal running \`bouncer watch\`)`);
  for (const file of rcFiles()) {
    backup(file);
    editRc(file, true);
    console.log(`✓ PATH        ${file}`);
  }

  console.log(`
Done. Builds started from NEW shells and NEW agent sessions now go through Bouncer.
Sessions that were already open keep their old PATH until restarted.

  bouncer status        what's running, what's waiting, and why
  BOUNCER_BYPASS=1 cmd  skip the gate once
  bouncer uninstall     remove everything (keeps ~/.bouncer history unless --purge)`);
}

export function uninstall(args: string[]): void {
  bootoutAndWait(`gui/${process.getuid?.() ?? 501}`);
  rmSync(plistPath, { force: true });
  console.log("✓ daemon stopped and removed from launchd");
  for (const file of settingsFiles()) {
    backup(file);
    editHooks(file, false);
    editStatusLine(file, false);
    console.log(`✓ hooks and statusline segment removed from ${file}`);
  }
  if (existsSync(cmuxDock)) {
    backup(cmuxDock);
    editCmuxDock(false);
    console.log(`✓ cmux dock control removed`);
  }
  for (const file of rcFiles()) {
    if (!readFileSync(file, "utf8").includes(RC_START)) continue;
    backup(file);
    editRc(file, false);
    console.log(`✓ PATH line removed from ${file}`);
  }
  rmSync(paths.shimDir, { recursive: true, force: true });
  console.log("✓ shims removed");
  if (args.includes("--purge")) {
    rmSync(paths.home, { recursive: true, force: true });
    console.log(`✓ ${paths.home} deleted`);
  }
}
